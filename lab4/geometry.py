"""Вершины, текстурные координаты и внешние единичные нормали граней."""

from dataclasses import dataclass
import math


@dataclass(frozen=True)
class Face:
    vertices: tuple
    normal: tuple
    uv: tuple


def make_face(*vertices):
    """Нормаль: векторное произведение двух рёбер, затем нормализация."""
    a, b, c = vertices[:3]
    u = tuple(b[i] - a[i] for i in range(3))
    v = tuple(c[i] - a[i] for i in range(3))
    cross = (u[1]*v[2] - u[2]*v[1], u[2]*v[0] - u[0]*v[2], u[0]*v[1] - u[1]*v[0])
    length = math.sqrt(sum(value*value for value in cross))
    if length == 0:
        raise ValueError("Вырожденная грань не имеет нормали")
    normal = tuple(value / length for value in cross)
    uv = ((0, 0), (1, 0), (0.5, 1)) if len(vertices) == 3 else ((0, 0), (1, 0), (1, 1), (0, 1))
    return Face(tuple(vertices), normal, uv)


